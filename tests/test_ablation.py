def test_sensitivity_suite_covers_every_declared_param_and_sweeps_fresh_clips():
    # Small ranges only, to keep this test fast -- the real sweep ranges are
    # exercised by running calibration/ablation.py directly.
    from calibration import ablation as ablation_module

    original_scalar = ablation_module.SCALAR_SWEEPS
    original_tuple = ablation_module.TUPLE_SWEEPS
    try:
        ablation_module.SCALAR_SWEEPS = {"max_speed_px_per_frame": [50.0, 110.0, 500.0]}
        ablation_module.TUPLE_SWEEPS = {("plausible_size", "lo"): [0.0, 50.0, 300.0]}
        results = run_sensitivity_suite(DATA_DIR, CLIP_IDS)
    finally:
        ablation_module.SCALAR_SWEEPS = original_scalar
        ablation_module.TUPLE_SWEEPS = original_tuple

    assert set(results) == {"max_speed_px_per_frame", "plausible_size.lo"}
    for series in results.values():
        points = series["points"]
        assert len(points) == 3
        assert any(p["is_default"] for p in points)
        for p in points:
            pct = p["outcome"]["pct"]
            assert abs(sum(pct.values()) - 1.0) < 1e-9
            assert 0.0 <= pct["kept"] <= 1.0
            assert 0.0 <= pct["interpolated"] <= 1.0
        verdict = series["verdict"]
        assert verdict["kept_pct_range"][0] <= verdict["kept_pct_range"][1]


def test_scalar_and_tuple_sweep_ranges_include_the_hand_config_default():
    defaults = hand_config()
    for param, values in SCALAR_SWEEPS.items():
        assert getattr(defaults, param) in values, f"{param} default not in its own sweep range"
    for (param, side), values in TUPLE_SWEEPS.items():
        lo, hi = getattr(defaults, param)
        default = lo if side == "lo" else hi
        assert default in values, f"{param}.{side} default not in its own sweep range"


def test_discover_clip_ids_still_finds_all_39():
    assert len(discover_clip_ids(DATA_DIR)) == 39

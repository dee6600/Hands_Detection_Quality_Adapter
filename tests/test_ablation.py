"""Ablation/sensitivity tooling (`calibration/ablation.py`) -- structural
checks against a small clip subset (fast), same pattern as
`test_sweep_thresholds.py`. The full 39-clip report is generated by running
the module directly (`python calibration/ablation.py`), not on every test run.

Every test that compares two configs loads a FRESH `ClipData` for each one
(`_classify` below always calls `load_clip` itself) -- reusing `Detection`
objects across configs would silently carry stage tags forward from the
first run, per this codebase's own documented gotcha (see
`calibration/ablation.py`'s module docstring and `EVAL_LOG.md`).
"""

import os

from adapter.hand_config import hand_config
from adapter.ingest import load_clip
from calibration.ablation import (
    ABLATIONS,
    OUTCOME_KEYS,
    SCALAR_SWEEPS,
    TUPLE_SWEEPS,
    classify_clip,
    outcome_summary,
    run_ablation_suite,
    run_dataset,
    run_sensitivity_suite,
)
from calibration.sweep_thresholds import discover_clip_ids

DATA_DIR = os.path.join(os.path.dirname(__file__), "..", "data")
CLIP_IDS = ["0c54a47b_t010", "407258cd_t036"]


def _classify(cid, config):
    clip = load_clip(os.path.join(DATA_DIR, cid))
    return classify_clip(clip, config)


def _raw_and_fabricated_total(cid, config):
    """Independent recomputation of the true total (raw + fabricated),
    deliberately not calling `classify_clip`, mirroring
    `test_sweep_thresholds.py`'s equivalent cross-check.
    """
    from adapter.association import track_detections
    from adapter.geometric import apply_stage1
    from adapter.interpolation import apply_stage4
    from adapter.temporal import apply_stage3

    clip = load_clip(os.path.join(DATA_DIR, cid))
    raw_total = sum(len(dets) for dets in clip.detections)
    stage1_frames = [apply_stage1(list(d), config) for d in clip.detections]
    tracks = track_detections(stage1_frames, config)
    before = sum(len(t.detections) for t in tracks)
    apply_stage3(tracks, clip.pose, config)
    apply_stage4(tracks, config, frame_count=len(clip.detections))
    after = sum(len(t.detections) for t in tracks)
    return raw_total + (after - before)


def test_classify_clip_accounts_for_every_detection():
    config = hand_config()
    for cid in CLIP_IDS:
        counts = _classify(cid, config)
        assert sum(counts.values()) == _raw_and_fabricated_total(cid, config)
        assert all(n >= 0 for n in counts.values())


